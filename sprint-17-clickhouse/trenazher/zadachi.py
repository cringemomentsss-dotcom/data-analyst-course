def window_funnel(events, steps, window_seconds, user_col="user_id",
                  name_col="event_name", ts_col="ts"):
    """Аналог windowFunnel: максимальный достигнутый уровень пользователя.

    Возвращает {user_id: уровень}, где уровень — сколько шагов подряд
    удалось пройти. Пользователи, не сделавшие первый шаг, получают 0.

    Правила, ровно как в ClickHouse:

    - шаги идут по возрастанию времени;
    - между шагами могут быть посторонние события;
    - **вся цепочка должна уложиться в window_seconds от первого шага**;
    - если первый шаг встречается несколько раз, берётся лучшая попытка.

    Реализация: для каждого вхождения первого шага идёшь вперёд по
    событиям пользователя, пока не вышел за окно, и продвигаешь
    счётчик, встречая следующий ожидаемый шаг.

    Третье правило — то, ради чего эта задача существует. Самописная
    воронка из спринта 13 сравнивала **первые вхождения** каждого шага
    за всё время. windowFunnel требует последовательность внутри окна.
    Это разные вопросы, и они дают разные числа на одних данных.
    В проекте эта разница обязательно всплывёт, и её надо будет
    объяснить, а не списать на ошибку.
    """
    raise NotImplementedError


