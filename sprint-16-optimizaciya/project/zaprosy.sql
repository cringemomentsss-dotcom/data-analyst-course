-- Шесть медленных запросов. Проект спринта 16.
--
-- Замеры сделаны на схеме dwh: 8 млн событий, 4 млн позиций, 1,5 млн заказов,
-- PostgreSQL 17 в Docker, настройки по умолчанию. У тебя числа будут другими —
-- важны не абсолютные значения, а порядок величины и во сколько раз стало быстрее.
--
-- Перед замером: \timing on
-- Прогоняй каждый запрос дважды и бери второй результат: первый греет кэш.

SET search_path TO dwh, public;


-- ===========================================================================
-- Q1. Отчёт «события за март»                              было ~1,7 с
-- ===========================================================================
SELECT count(*) AS events, sum(revenue) AS revenue
FROM events
WHERE date_trunc('month', event_ts) = '2026-03-01';


-- ===========================================================================
-- Q2. Сверка заказов: сколько позиций в каждом            было ~38 с
-- ===========================================================================
SELECT o.order_id,
       o.total_amount,
       (SELECT count(*) FROM order_lines l WHERE l.order_id = o.order_id) AS lines
FROM orders o
WHERE o.created_at >= '2026-06-01'
  AND o.status = 'paid'
LIMIT 200;


-- ===========================================================================
-- Q3. Поиск заказов пользователя из формы поддержки       было ~240 мс
-- ===========================================================================
SELECT count(*)
FROM orders
WHERE user_id::text = '12345';


-- ===========================================================================
-- Q4. Постраничный экспорт событий, страница 80 000       было ~2,3 с
-- ===========================================================================
SELECT event_id, event_ts, event_name
FROM events
ORDER BY event_ts
LIMIT 50 OFFSET 4000000;


-- ===========================================================================
-- Q5. Заказы без позиций                    НЕ ЗАВЕРШАЕТСЯ (>10 минут)
-- ===========================================================================
-- ВНИМАНИЕ: не жди его. Сними через полминуты (Ctrl+C) и разбери план
-- через EXPLAIN без ANALYZE — он строится за доли секунды.
-- Это отдельный навык: диагностировать запрос, который нельзя выполнить.
SELECT count(*)
FROM orders o
WHERE o.created_at >= '2026-06-01'
  AND o.order_id NOT IN (SELECT order_id FROM order_lines);


-- ===========================================================================
-- Q6. Запрос дашборда: события по дням и устройствам      было ~17 с
-- ===========================================================================
-- Выполняется при каждом открытии дашборда. Открывают его двенадцать человек,
-- некоторые по нескольку раз в день.
SELECT date_trunc('day', event_ts)::date AS d,
       device,
       count(*)                 AS events,
       count(DISTINCT user_id)  AS users,
       sum(revenue)             AS revenue
FROM events
GROUP BY 1, 2
ORDER BY 1, 2;
