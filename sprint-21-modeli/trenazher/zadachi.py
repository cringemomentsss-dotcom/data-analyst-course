def psi(expected, actual, bins=10):
    """Population Stability Index: насколько распределение уехало.

    Разбей эталонное распределение на квантильные корзины, посчитай доли
    в обоих распределениях и просуммируй (доля_факт − доля_эталон) ×
    ln(доля_факт / доля_эталон). Доли обрезай снизу малым числом, чтобы
    не делить на ноль. Если границ корзин получилось меньше трёх —
    верни None.

    Возвращает {'psi', 'verdict', 'action', 'bins'}:

    | PSI | вердикт |
    |---|---|
    | меньше 0,1 | 'стабильно' |
    | 0,1–0,25 | 'заметный сдвиг' |
    | выше 0,25 | 'сильный сдвиг' |

    **Модель, работавшая полгода назад, сегодня врёт** — и врёт молча.
    Метрики качества посчитать нельзя: правильных ответов для свежих
    данных ещё нет, они появятся через горизонт прогноза. PSI —
    единственное, что можно измерить сегодня: он смотрит не на качество,
    а на то, изменились ли входные данные.

    Сильный сдвиг означает, что модель применяется к людям, не похожим
    на тех, на ком она училась. Её прогнозам верить нельзя, даже если
    последний замер качества был отличным.
    """
    raise NotImplementedError
